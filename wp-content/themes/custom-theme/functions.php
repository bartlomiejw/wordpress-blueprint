<?php
/**
 * Custom Theme bootstrap: theme supports, assets and block registration.
 *
 * @package CustomTheme
 */

declare( strict_types=1 );

namespace CustomTheme;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

define( 'CUSTOM_THEME_DIR', get_template_directory() );
define( 'CUSTOM_THEME_URI', get_template_directory_uri() );
define( 'CUSTOM_THEME_VERSION', wp_get_theme()->get( 'Version' ) ?: '0.0.0' );

add_action( 'after_setup_theme', __NAMESPACE__ . '\\setup' );
add_action( 'wp_enqueue_scripts', __NAMESPACE__ . '\\enqueue_assets' );
add_action( 'init', __NAMESPACE__ . '\\register_blocks' );

/**
 * Declare theme supports.
 */
function setup(): void {
	add_theme_support( 'post-thumbnails' );
	add_theme_support( 'title-tag' );
	add_theme_support( 'html5', [ 'search-form', 'comment-form', 'comment-list', 'gallery', 'caption', 'style', 'script' ] );
}

/**
 * Enqueue compiled front-end assets.
 *
 * Dependencies and cache-busting versions come from the *.asset.php files
 * generated by @wordpress/scripts, so they always match the build.
 */
function enqueue_assets(): void {
	$css_asset = asset_meta( 'css/main' );
	$js_asset  = asset_meta( 'js/main' );

	wp_enqueue_style(
		'custom-theme-main',
		CUSTOM_THEME_URI . '/assets/dist/css/main.css',
		[],
		$css_asset['version']
	);
	wp_style_add_data( 'custom-theme-main', 'rtl', 'replace' );

	wp_enqueue_script(
		'custom-theme-main',
		CUSTOM_THEME_URI . '/assets/dist/js/main.js',
		$js_asset['dependencies'],
		$js_asset['version'],
		[
			'in_footer' => true,
			'strategy'  => 'defer',
		]
	);
}

/**
 * Read the generated asset metadata for a build entry point.
 *
 * @param string $entry Entry point relative to assets/dist, without extension.
 * @return array{dependencies: list<non-empty-string>, version: string}
 */
function asset_meta( string $entry ): array {
	$file = CUSTOM_THEME_DIR . '/assets/dist/' . $entry . '.asset.php';
	$meta = is_readable( $file ) ? require $file : [];

	$dependencies = is_array( $meta['dependencies'] ?? null ) ? $meta['dependencies'] : [];
	$version      = $meta['version'] ?? null;

	return [
		'dependencies' => array_values(
			array_filter(
				$dependencies,
				static fn ( mixed $handle ): bool => is_string( $handle ) && '' !== $handle
			)
		),
		'version'      => is_string( $version ) ? $version : CUSTOM_THEME_VERSION,
	];
}

/**
 * Register every compiled block in build/blocks/{name}/block.json.
 */
function register_blocks(): void {
	$block_dirs = glob( CUSTOM_THEME_DIR . '/build/blocks/*/block.json' );

	if ( ! $block_dirs ) {
		return;
	}

	foreach ( $block_dirs as $block_json ) {
		register_block_type( dirname( $block_json ) );
	}
}
